-- word_similarity matches the input against the closest run of words inside the
-- official name, so 'Cali' scores 1.0 against 'SANTIAGO DE CALI'. Ties are broken
-- by whole-name similarity (exact names first), then by department match.
CREATE OR REPLACE FUNCTION dane_find_municipality(p_city text, p_state text DEFAULT NULL)
RETURNS TABLE (
  city_code   CHAR(5),
  state_code  CHAR(2),
  city_name   TEXT,
  state_name  TEXT,
  score       REAL,
  state_match BOOLEAN
)
LANGUAGE sql
STABLE
AS $$
  WITH input AS (
    SELECT dane_normalize(p_city) AS city, nullif(dane_normalize(p_state), '') AS state
  )
  SELECT m.city_code, m.state_code, m.city_name, m.state_name,
         word_similarity(i.city, m.city_name_normalized) AS score,
         coalesce(word_similarity(i.state, m.state_name_normalized) >= 0.6, false) AS state_match
  FROM dane_municipality m, input i
  WHERE i.city <> ''
    AND word_similarity(i.city, m.city_name_normalized) >= 0.5
  ORDER BY state_match DESC,
           score DESC,
           similarity(i.city, m.city_name_normalized) DESC,
           m.city_code
  LIMIT 5
$$;
