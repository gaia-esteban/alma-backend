-- DANE DIVIPOLA municipality catalog, for fuzzy city-name -> DANE code lookup.
-- Used to fill Siigo's supplier address.city.state_code / city_code
-- (POST /v1/customers) from the free-text city name stored on invoices.
--
-- Source: datos.gov.co dataset gdxc-w37w "DIVIPOLA - Códigos municipios" (DANE),
-- 1122 rows (municipios, áreas no municipalizadas, islas), fetched 2026-11-01.
--
-- Requires pg_trgm. It's a trusted extension on PostgreSQL 13+, so the database
-- owner can create it without superuser; on managed Postgres it's allow-listed.
-- Accent stripping is done with translate() instead of the unaccent extension
-- so the normalizer can be IMMUTABLE and used in a generated column + index.
--
-- Usage:
--   SELECT * FROM dane_find_municipality('Bogota');                 -- 11001 / 11
--   SELECT * FROM dane_find_municipality('La Union', 'Valle');      -- department disambiguates
-- Returns up to 5 candidates, best first. Callers should treat the result as
-- ambiguous when the top two have the same score and different departments
-- (e.g. 'Granada' exists in 4 departments) and no department was given.
-- PostgreSQL

CREATE EXTENSION IF NOT EXISTS pg_trgm;

-- lowercase, strip Spanish accents, punctuation -> space, collapse spaces.
-- "BOGOTÁ, D.C." -> "bogota d c"
CREATE OR REPLACE FUNCTION dane_normalize(p_text text)
RETURNS text
LANGUAGE sql
IMMUTABLE
PARALLEL SAFE
AS $$
  SELECT btrim(regexp_replace(
    translate(lower(coalesce(p_text, '')), 'áàäâéèëêíìïîóòöôúùüûñç', 'aaaaeeeeiiiioooouuuunc'),
    '[^a-z0-9]+', ' ', 'g'
  ))
$$;

CREATE TABLE IF NOT EXISTS dane_municipality (
  city_code             CHAR(5) PRIMARY KEY,   -- DANE código municipio, e.g. 11001
  state_code            CHAR(2) NOT NULL,      -- DANE código departamento, e.g. 11
  city_name             TEXT    NOT NULL,      -- official name, e.g. BOGOTÁ, D.C.
  state_name            TEXT    NOT NULL,
  city_name_normalized  TEXT GENERATED ALWAYS AS (dane_normalize(city_name)) STORED,
  state_name_normalized TEXT GENERATED ALWAYS AS (dane_normalize(state_name)) STORED
);

CREATE INDEX IF NOT EXISTS idx_dane_municipality_city_trgm
  ON dane_municipality USING gin (city_name_normalized gin_trgm_ops);

